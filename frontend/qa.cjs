const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const env = fs.readFileSync(path.join(root, '.env'), 'utf8')
function password(role) {
  const matched = env.match(new RegExp(`^DEMO_${role}_PASSWORD=(.*)$`, 'm'))
  if (!matched) throw new Error(`Missing local demo password for ${role}`)
  return matched[1].trim()
}

async function login(page, role) {
  await page.locator('input[autocomplete="username"]').fill(`${role.toLowerCase()}.demo`)
  await page.locator('input[autocomplete="current-password"]').fill(password(role))
  await page.getByRole('button', { name: '进入工作台' }).click()
  await page.getByRole('heading', { name: '质量任务总览' }).waitFor()
}

async function main() {
  const browser = await chromium.launch({ headless: true,
    executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 940 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/')
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-login.png'), fullPage: true })
  await login(page, 'INSPECTOR')
  if (await page.getByRole('button', { name: '审批中心' }).count()) throw Error('Inspector can see approval navigation')
  await page.getByRole('button', { name: '新建检测' }).click()
  await page.locator('select').first().selectOption('BA-2026-1003')
  await page.locator('input[type="file"]').setInputFiles(path.join(root, 'design', 'preview-report.png'))
  await page.getByRole('button', { name: '提交检测任务' }).click()
  await page.locator('.detail-summary .badge').filter({ hasText: '待审批' }).waitFor({ timeout: 150000 })
  const taskId = (await page.locator('.section-head .overline').textContent()).split('/').at(-1).trim()
  if (!taskId.startsWith('QI-')) throw Error('Task id missing after upload')
  await page.getByRole('heading', { name: '调查报告' }).waitFor({ timeout: 10000 })
  await page.locator('.tool-trace summary').click()
  if (await page.locator('.tool-trace tbody tr').count() < 3) throw Error('Read-only tool trace missing')
  await page.locator('.evidence-links button').first().click()
  await page.getByText('EVIDENCE SOURCE').waitFor({ timeout: 5000 })
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-report.png'), fullPage: true })
  await page.getByRole('button', { name: '退出登录' }).click()

  await login(page, 'ENGINEER')
  await page.locator('tr').filter({ hasText: taskId }).getByRole('button', { name: '查看详情' }).click()
  await page.locator('.approval-form textarea').fill('工程师核对检测与批次来源，同意提交主管复核')
  await page.getByRole('button', { name: '批准并送主管复核' }).click()
  await page.getByText('当前阶段：质量主管', { exact: false }).waitFor()
  if (await page.locator('.approval-form').count()) throw Error('Engineer can co-sign manager stage')
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-approval.png'), fullPage: true })
  await page.getByRole('button', { name: '退出登录' }).click()

  await login(page, 'MANAGER')
  await page.locator('tr').filter({ hasText: taskId }).getByRole('button', { name: '查看详情' }).click()
  await page.locator('.approval-form textarea').fill('主管独立核对证据及工程师意见，同意启动处置')
  await page.getByRole('button', { name: '提交审批决定' }).click()
  await page.locator('.detail-summary .badge').filter({ hasText: '已创建工单' }).waitFor()
  await page.getByRole('heading', { name: '工单处置' }).waitFor({ timeout: 10000 })
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-order.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-mobile.png'), fullPage: true })
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile horizontal overflow')
  await page.setViewportSize({ width: 1440, height: 940 })
  await page.getByRole('button', { name: '退出登录' }).click()
  await login(page, 'ADMIN')
  await page.getByRole('button', { name: '用户与权限' }).click()
  await page.getByRole('heading', { name: '本租户账户' }).waitFor()
  const account = `qa.frontend.${Date.now()}`
  await page.getByLabel('账号').fill(account)
  await page.getByLabel('姓名').fill('前端联调用户')
  await page.getByLabel('创建原因').fill('验证管理员建号与首次改密流程')
  await page.getByRole('button', { name: '创建账户' }).click()
  const temporaryPassword = await page.locator('.one-time code').textContent()
  if (!temporaryPassword || temporaryPassword.length < 12) throw Error('One-time password missing')
  await page.getByRole('button', { name: '我已记录，隐藏密码' }).click()
  await page.screenshot({ path: path.join(root, 'design', 'preview-react-admin.png'), fullPage: true })
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.locator('input[autocomplete="username"]').fill(account)
  await page.locator('input[autocomplete="current-password"]').fill(temporaryPassword)
  await page.getByRole('button', { name: '进入工作台' }).click()
  await page.getByRole('heading', { name: '首次登录请修改密码' }).waitFor()
  await page.locator('input[autocomplete="current-password"]').fill(temporaryPassword)
  await page.locator('input[autocomplete="new-password"]').fill(`qa-changed-password-${Date.now()}`)
  await page.getByRole('button', { name: '保存新密码' }).click()
  await page.getByRole('heading', { name: '质量任务总览' }).waitFor()
  if (errors.length) throw Error(errors.join('; '))
  console.log(`React UI flow passed: upload ${taskId}, report evidence, co-sign, work order, admin creation, first password change, mobile layout.`)
  await browser.close()
}

main().catch(error => { console.error(error); process.exit(1) })
